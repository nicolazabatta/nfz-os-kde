# Boot-time rules (tmpfiles.d) for the folders packages created in /var.
# bootc copies the image's /var only on the first install; upgrades never touch
# /var. A package added in a later version therefore finds its /var folders
# missing on an existing machine unless a tmpfiles.d rule creates them at boot.
# Runs last, so it sees everything the packages and scripts put in /var.
out=/usr/lib/tmpfiles.d/nfz-var.conf

# dnf's download statistics: not needed in the image
rm -f /var/lib/dnf/repos/*/countme

# Paths that already have a tmpfiles.d rule (from systemd, the base image, ...)
covered=$(systemd-tmpfiles --cat-config | awk '!/^#/ && NF >= 2 {print $2}' | sort -u)

# One `d` rule per folder not yet covered, with its current mode and owner.
# /var/cache, /var/log and /var/tmp are emptied after the scripts, so skipped.
echo "# Generated by scripts/90-var-tmpfiles.sh at build time" > "$out"
find /var -mindepth 1 \
    \( -path /var/cache -o -path /var/log -o -path /var/tmp \) -prune \
    -o -type d -print | sort | while read -r dir; do
    if grep -qxF "$dir" <<< "$covered"; then continue; fi
    line=$(stat -c 'd %n %a %U %G - -' "$dir")
    case "$line" in
        *UNKNOWN*) echo "ERROR: $dir has an owner without a name" >&2; exit 1 ;;
    esac
    echo "$line" >> "$out"
done
echo "tmpfiles.d rules written: $(grep -c '^d ' "$out") (in $out)"
